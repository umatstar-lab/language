namespace Akeeba\Component\AdminTools\Administrator\Model;

defined('_JEXEC') or die;

use Akeeba\Component\AdminTools\Administrator\Helper\IpExpressionValidator;
use Akeeba\Component\AdminTools\Administrator\Helper\ServerTechnology;
use DateTimeZone;
use Joomla\CMS\Factory;

#[\AllowDynamicProperties]
class WebconfigmakerModel extends ServerconfigmakerModel
{

	/**
	 * The current configuration of this feature
	 *
	 * @var  object
	 */
	protected $configKey = 'wcconfig';

	/**
	 * The base name of the configuration file being saved by this feature, e.g. ".htaccess". The file is always saved
	 * in the site's root. Any old files under that name are renamed with a .admintools suffix.
	 *
	 * @var string
	 */
	protected $configFileName = 'web.config';

	/**
	 * A rewrite rule condition for a folder URL: the folder has no index.php. {REQUEST_FILENAME} of a folder URL ends in
	 * a backslash, e.g. C:\inetpub\wwwroot\foo\, so index.php is appended without one.
	 *
	 * @var string
	 */
	private const NO_INDEX_PHP_CONDITION = "\n\t\t\t\t\t\t"
		. '<add input="{REQUEST_FILENAME}index.php" matchType="IsFile" ignoreCase="false" negate="true" />';

	/**
	 * The default documents a server may use when the web.config sets none (fileorder=0): IIS's own default list, in its
	 * order, plus index.php, which PHP Manager and the Web Platform Installer add on a typical PHP-on-IIS host.
	 *
	 * @var string[]
	 */
	private const SERVER_DEFAULT_DOCUMENTS = [
		'default.htm', 'default.asp', 'index.htm', 'index.html', 'iisstart.htm', 'default.aspx', 'index.php',
	];

	/** @inheritdoc  */
	public function isSupported(): int
	{
		return ServerTechnology::isWebConfigSupported();
	}

	/**
	 * Compile and return the contents of the web.config configuration file
	 *
	 * @return string
	 */
	public function makeConfigFile()
	{
		// Make sure we are called by an expected caller
		ServerTechnology::checkCaller($this->allowedCallersForMake);

		$app = Factory::getApplication();

		$timezone = 'UTC';

		// Fetch the timezone from the user only if we're not in CLI
		if (!$app->isClient('cli'))
		{
			$timezone = $app->getIdentity()->getParam('timezone', $app->get('offset', 'UTC'));
		}

		$date = clone Factory::getDate();
		$tz   = new DateTimeZone($timezone);
		$date->setTimezone($tz);
		$d       = $date->format('Y-m-d H:i:s T', true);
		$version = ADMINTOOLS_VERSION;

		$webConfig = <<< XML
<?xml version="1.0" encoding="utf-8"?>
<!--
	Security Enhanced & Highly Optimized .web.config File for Joomla!
	automatically generated by Admin Tools $version on $d

	Admin Tools is Free Software, distributed under the terms of the GNU
	General Public License version 3 or, at your option, any later version
	published by the Free Software Foundation.

	!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!! IMPORTANT !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
	!!                                                                       !!
	!!  If you get an Internal Server Error 500 or a blank page when trying  !!
	!!  to access your site, remove this file and try tweaking its settings  !!
	!!  in the back-end of the Admin Tools component.                        !!
	!!                                                                       !!
	!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
-->
<configuration>
	<system.webServer>

XML;

		// The exceptions go through normaliseDirectories(), so that every rule below sees the same entries (gh-454)
		$config = $this->normaliseExceptions($this->loadConfiguration());

		/**
		 * The site's path ("Base directory of your site"), as it is, e.g. my site (gh-462). The redirect targets have it
		 * URL-encoded, e.g. my%20site: IIS puts them in the Location header as they are, and a raw space makes an invalid
		 * header. The {UNENCODED_URL} pattern of "Redirect index.php to /" matches it as the browser sends it.
		 *
		 * A path with a double quote, a backslash or a control character, none of which a Windows folder name can have,
		 * is refused like the NginX Conf Maker does (gh-454): the file refuses every request and says why.
		 */
		$sitePath = trim((string) ($config->rewritebase ?? ''), '/');

		if (preg_match('/["\\\\[:cntrl:]]/', $sitePath))
		{
			return $webConfig . <<<XML
		<!--
			NOT GENERATED: the site's path (Base directory of your site) has a double quote, a backslash or a control
			character, which no folder of a Windows server can have. Every request is refused. Correct the Base
			directory of your site, or delete this file, then make this file again.
		-->
		<rewrite>
			<rules>
				<clear />
				<rule name="The site's path cannot be written: refuse every request" stopProcessing="true">
					<match url=".*" />
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>
			</rules>
		</rewrite>
	</system.webServer>
</configuration>

XML;
		}

		/**
		 * Let's start with IP restriction. An empty list writes nothing (gh-466), see restrictIpList(): it is a
		 * misconfiguration, which the maker's page warns about. It wrote an <ipSecurity> with allowUnlisted="false"
		 * and no entry, which refused everyone. Without the restriction, the TRACE and TRACK block
		 * goes where it goes with "None".
		 */
		$restrictIPList = $this->restrictIpList($config);
		$restrictIP     = empty($restrictIPList) ? 'none' : $config->restrictip;

		if ($restrictIP !== 'none')
		{
			$ipRules = '';
			foreach ($restrictIPList as $ipRange)
			{
				[$ip, $subNet] = $this->ipRangeToIPandNetmask($ipRange);
				$ipRules .= "\t\t\t\t<remove ipAddress=\"$ip\" subnetMask=\"$subNet\" />\n";
				$ipRules .= "\t\t\t\t<add ipAddress=\"$ip\" subnetMask=\"$subNet\" allowed=\"true\" />\n";
			}

			$requestFilteringRules = '';

			if ($config->notracetrack == 1)
			{
				$requestFilteringRules = <<<XML
			<!-- Disable HTTP methods TRACE and TRACK (protect against XST) -->
			<requestFiltering>
				<verbs>
					<remove verb="TRACE" />
					<add verb="TRACE" allowed="false" />
					<remove verb="TRACK" />
					<add verb="TRACK" allowed="false" />
				</verbs>
			</requestFiltering>
XML;
			}

			$webConfig .= <<< END
		<security>
			<!-- Restricted access by IP address -->
			<ipSecurity allowUnlisted="false" denyAction="Forbidden">
$ipRules
			</ipSecurity>
			$requestFilteringRules
		</security>
END;

		}


		/**
		 * With front-end protection on, by default, index.php is only the default document in the Joomla! folders (see
		 * the "Default document" rewrite rule) and in the full-access folders (see the <location> elements at the end).
		 * Otherwise, a request for any folder URL, e.g. /foo/, runs foo/index.php, and the Server Protection rules only
		 * see the folder URL, foo/.
		 *
		 * Without front-end protection, any index.php runs when requested directly anyway. index.php stays a site-wide
		 * default document, so a PHP application in a subfolder works without being listed in the full-access folders.
		 */
		$indexPhpEverywhere = $config->frontendprot != 1 || ($config->fileorderscope ?? 'joomla') === 'all';

		if ($config->fileorder == 1)
		{
			$indexPhp  = $indexPhpEverywhere ? "\n\t\t\t\t<add value=\"index.php\" />" : '';
			$webConfig .= <<< XML
		<!-- File execution order -->
		<defaultDocument enabled="true">
			<files>
				<clear />$indexPhp
				<add value="index.html" />
				<add value="index.htm" />
			</files>
		</defaultDocument>

XML;
		}

		if ($config->nodirlists == 1)
		{
			$webConfig .= <<< XML
		<!-- No directory listings -->
		<directoryBrowse enabled="false" />

XML;
		}

		/**
		 * A web.config may only have one <staticContent>: everything which goes in it is collected here first.
		 */
		$staticComment = '';
		$staticContent = '';

		if ($config->exptime != 0)
		{
			$setEtag  = ($config->etagtype == 'none') ? 'setEtag="false"' : '';
			$eTagInfo = ($config->etagtype == 'none') ? '// Send ETag: false (IIS only supports true/false for ETags)' : '';

			/**
			 * Every static file gets the most common expiration time, which the outbound rules below then change per file
			 * type, so that it matches the .htaccess Maker; see expirationRules(). Only IIS' static file handler reads
			 * <staticContent>: the output of PHP files is never cached by these rules.
			 *
			 * IIS reads cacheControlMaxAge as a timespan, [-][d.]hh:mm:ss[.ff], not as a number of seconds. Seconds make
			 * IIS refuse every request for a static file with HTTP 500.19.
			 */
			$expTime = $this->secondsToTimespan($this->expirationTimes($config)['default']);

			$staticComment = "\t\t<!-- Optimal default expiration time $eTagInfo -->\n";
			$staticContent .= "\t\t\t<clientCache cacheControlMode=\"UseMaxAge\" cacheControlMaxAge=\"$expTime\" $setEtag />\n";
		}
		elseif ($config->etagtype == 'none')
		{
			/**
			 * Without an expiration time, "Send ETag: None" still needs its own <clientCache>, without any cache control:
			 * setEtag is an attribute of <clientCache>.
			 */
			$staticComment = "\t\t<!-- Send ETag: false (IIS only supports true/false for ETags) -->\n";
			$staticContent .= "\t\t\t<clientCache setEtag=\"false\" />\n";
		}

		if ($config->frontendprot == 1)
		{
			/**
			 * Front-end protection always allows site.webmanifest in the site's root (ROOT_STATIC_FILES, gh-469), but IIS
			 * only serves the file types it has a MIME type for, and out of the box it has none for .webmanifest: it
			 * answered with HTTP 404.3. IIS refuses a MIME type added twice under the same file extension, e.g. by the
			 * server's configuration or a parent folder's web.config, with HTTP 500.19 for every request: <remove> first.
			 */
			$staticContent .= <<< XML
			<!-- Serve web app manifests, e.g. site.webmanifest -->
			<remove fileExtension=".webmanifest" />
			<mimeMap fileExtension=".webmanifest" mimeType="application/manifest+json" />

XML;
		}

		if ($staticContent !== '')
		{
			$webConfig .= $staticComment . "\t\t<staticContent>\n" . $staticContent . "\t\t</staticContent>\n\n";
		}

		if ($config->autocompress == 1)
		{
			$webConfig .= <<<XML
		<urlCompression doStaticCompression="false" doDynamicCompression="true" />
		<httpCompression>
			<dynamicTypes>
				<clear />
				<add mimeType="text/*" enabled="true" />
				<add mimeType="message/*" enabled="true" />
				<add mimeType="application/xml" enabled="true" />
				<add mimeType="application/xhtml+xml" enabled="true" />
				<add mimeType="application/rss+xml" enabled="true" />
				<add mimeType="application/javascript" enabled="true" />
				<add mimeType="text/javascript" enabled="true" />
				<add mimeType="application/x-javascript" enabled="true" />
				<add mimeType="image/svg+xml" enabled="true" />
				<add mimeType="*/*" enabled="false" />
			</dynamicTypes>
		</httpCompression>

XML;
		}


		$webConfig .= <<< XML
		<rewrite>
			<rules>
				<clear />

XML;

		/**
		 * Blank entries are skipped: with blank entries only there is no rule at all, as a condition with an empty pattern
		 * would block every request. So are duplicates, regardless of letter case, see normaliseUserAgents().
		 *
		 * Like the .htaccess and NginX makers since gh-461 (gh-462): an entry with a control character other than white
		 * space is skipped, as most of them are not allowed in XML at all, and one made the web.config invalid: IIS
		 * refused every request with HTTP 500.19. White space other than the space is written as \s, as XML turns a tab
		 * or a new line in an attribute into a space. An entry which is not a valid regular expression is skipped too:
		 * IIS answers every request with HTTP 500.52 when it cannot compile one pattern (measured). URL Rewrite's regular
		 * expressions are ECMAScript-like, not PCRE, so an entry must be valid PCRE (isValidRegex()) and have none of the
		 * PCRE-only syntax IIS refuses, see isIisRegex().
		 */
		$hoggerAgents = [];

		foreach ($this->normaliseUserAgents($config->hoggeragents ?? []) as $agent)
		{
			$regex = $this->blockedUserAgentRegex($agent);

			if ($regex !== null)
			{
				$hoggerAgents[] = $regex;
			}
		}

		if (!empty($hoggerAgents) && ($config->nohoggers == 1))
		{
			/**
			 * One condition per ten user agents, any of which blocks the request (MatchAny). The agents are regular
			 * expression fragments by design, e.g. maxthon$, so they are XML-escaped but never regex-quoted. Without XML
			 * escaping an agent with &, " or < makes the web.config invalid, and IIS refuses every request with 500.19.
			 *
			 * The groups of a regular expression are numbered across all of it, so the agents joined in a condition share
			 * the numbers: in (x)ybot|^(a)\1bot the \1 is the first agent's group, which never takes part when the
			 * second agent matches, and IIS then reads it as the empty string (measured, gh-463). The second agent
			 * blocked ^abot instead of ^aabot. Wrapping each agent in (?:…) does not change the numbering. An agent with
			 * a back-reference gets a condition of its own instead, after the others, where the numbers are its own.
			 * Such agents are rare, so this keeps the conditions about ten times fewer than the agents (gh-452), without
			 * renumbering back-references the way IIS would read them. The .htaccess and NginX makers write one
			 * condition per agent.
			 */
			$joined   = [];
			$isolated = [];

			foreach ($hoggerAgents as $agent)
			{
				if ($this->hasBackReference($agent))
				{
					$isolated[] = [$agent];

					continue;
				}

				$joined[] = $agent;
			}

			$chunks = array_merge(array_chunk($joined, 10), $isolated);

			$conditions = [];

			foreach ($chunks as $chunk)
			{
				$pattern      = htmlspecialchars(implode('|', $chunk), ENT_XML1 | ENT_QUOTES, 'UTF-8');
				$conditions[] = "\t\t\t\t\t\t" . '<add input="{HTTP_USER_AGENT}" pattern="' . $pattern . '" />';
			}

			$conditions = implode("\n", $conditions);

			$webConfig .= <<< XML
				<rule name="Common hacking tools and bandwidth hoggers block" stopProcessing="true">
					<match url=".*" />
					<conditions logicalGrouping="MatchAny" trackAllCaptures="false">
$conditions
					</conditions>
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden: Access is denied." statusDescription="You do not have permission to view this directory or page using the credentials that you supplied." />
				</rule>

XML;
		}

		if ($config->autoroot)
		{
			/**
			 * Like the .htaccess Maker's rule: only a request for the site's index.php itself, as the client sent it,
			 * without a query string or path info, and not a POST. {UNENCODED_URL} is the URL as requested, query string
			 * included, before any rewrite, so a request for / which IIS or the "Default document" rule turns into
			 * index.php is not redirected back to / in a loop.
			 *
			 * The target is relative to the domain: IIS makes it absolute with the request's scheme and Host header,
			 * which already carries any non-default port. {UNENCODED_URL} is not URL-decoded, and the target must be
			 * URL-encoded: both have the site's path as the browser sends it, e.g. %20 for a space (gh-462).
			 *
			 * Behind a reverse proxy or load balancer which terminates TLS, IIS receives plain HTTP, and would send an
			 * HTTPS visitor to http://. A first rule, for X-Forwarded-Proto: https (in any letter case: IIS conditions
			 * ignore case by default), redirects to an absolute https:// target instead. The .htaccess and NginX Makers'
			 * www and domain redirects honour that header too. A request IIS itself receives over HTTPS already gets an
			 * https:// target from the second rule.
			 */
			$base        = $sitePath === '' ? '' : '/' . $sitePath;
			$basePattern = htmlspecialchars($this->requestPathRegex($base), ENT_XML1 | ENT_QUOTES, 'UTF-8');
			$baseUrl     = htmlspecialchars($this->urlEncodedPath($base), ENT_XML1 | ENT_QUOTES, 'UTF-8');

			$webConfig .= <<<XML
				<rule name="Redirect index.php to / behind an HTTPS proxy" stopProcessing="true">
					<match url="^index\.php$" ignoreCase="false" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
						<add input="{REQUEST_METHOD}" pattern="^POST$" ignoreCase="false" negate="true" />
						<add input="{UNENCODED_URL}" pattern="^$basePattern/index\.php$" ignoreCase="false" />
						<add input="{HTTP_X_FORWARDED_PROTO}" pattern="^https$" />
					</conditions>
					<action type="Redirect" url="https://{HTTP_HOST}$baseUrl/" appendQueryString="false" redirectType="Permanent" />
				</rule>
				<rule name="Redirect index.php to /" stopProcessing="true">
					<match url="^index\.php$" ignoreCase="false" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
						<add input="{REQUEST_METHOD}" pattern="^POST$" ignoreCase="false" negate="true" />
						<add input="{UNENCODED_URL}" pattern="^$basePattern/index\.php$" ignoreCase="false" />
					</conditions>
					<action type="Redirect" url="$baseUrl/" appendQueryString="false" redirectType="Permanent" />
				</rule>

XML;
		}

		/**
		 * The www, non-www and old domain redirects go to another host, so their targets are absolute, and must carry the
		 * scheme the visitor used. Each redirect is two rules: one for a visitor on HTTPS, one for a visitor on HTTP.
		 *
		 * A visitor is on HTTPS when IIS itself received HTTPS ({HTTPS} is "on"; otherwise "off"), or when a reverse proxy
		 * or load balancer which terminates TLS says so with X-Forwarded-Proto: https. A rule's conditions either all
		 * have to match or any one of them, never a mix, so one condition tests both server variables at once, joined
		 * with a colon: "on:" or "off:https" is HTTPS. IIS conditions ignore case by default, which takes care of
		 * "HTTPS" as well. The HTTP rule tests the same input, negated.
		 *
		 * With trackAllCaptures off, {C:n} are the captures of the last condition which matched: the host condition
		 * comes last.
		 */
		$httpsInput   = '{HTTPS}:{HTTP_X_FORWARDED_PROTO}';
		$httpsPattern = '^on:|:https$';
		$schemes      = [
			'https' => sprintf('<add input="%s" pattern="%s" />', $httpsInput, $httpsPattern),
			'http'  => sprintf('<add input="%s" pattern="%s" negate="true" />', $httpsInput, $httpsPattern),
		];
		$schemeSuffix = ['https' => ' over HTTPS', 'http' => ''];

		/**
		 * A rule's match url, and so {R:1}, is relative to the folder of its web.config. For a site in a subfolder, every
		 * absolute target must add the subfolder back: "Base directory of your site". The host name fields may also hold
		 * the site's path, as our documentation used to tell users to type it there: only their host name part is used,
		 * so that the subfolder is never there twice. It is URL-encoded, see $sitePath above.
		 */
		$subfolder = $sitePath === ''
			? '' : htmlspecialchars($this->urlEncodedPath($sitePath), ENT_XML1 | ENT_QUOTES, 'UTF-8') . '/';

		switch ($config->wwwredir)
		{
			case 1:
				// non-www to www
				foreach ($schemes as $scheme => $schemeCondition)
				{
					$webConfig .= <<<END
				<rule name="Redirect non-www to www{$schemeSuffix[$scheme]}" stopProcessing="true">
					<match url="^(.*)$" ignoreCase="false" />
					<conditions logicalGrouping="MatchAll">
						$schemeCondition
						<add input="{HTTP_HOST}" pattern="^www\." negate="true" />
					</conditions>
					<action type="Redirect" url="$scheme://www.{HTTP_HOST}/$subfolder{R:1}" redirectType="Found" />
				</rule>

END;
				}
				break;

			case 2:
				// www to non-www
				foreach ($schemes as $scheme => $schemeCondition)
				{
					$webConfig .= <<<END
				<rule name="Redirect www to non-www{$schemeSuffix[$scheme]}" stopProcessing="true">
					<match url="^(.*)$" ignoreCase="false" />
					<conditions logicalGrouping="MatchAll">
						$schemeCondition
						<add input="{HTTP_HOST}" pattern="^www\.(.+)$" />
					</conditions>
					<action type="Redirect" url="$scheme://{C:1}/$subfolder{R:1}" redirectType="Found" />
				</rule>

END;
				}
				break;
		}

		/**
		 * Each old domain once, regardless of letter case and port (gh-470): each rule is named after its old domain, and
		 * IIS refuses two rules whose names only differ in letter case with HTTP 500 for every request.
		 */
		$domains = $this->normaliseOldDomains($config->olddomain ?? '');

		if (!empty($domains))
		{
			// Like the .htaccess Maker: HTTP visitors go to the HTTP host name, HTTPS visitors to the HTTPS one.
			$newDomains = [
				'https' => $this->hostWithoutPath((string) ($config->httpshost ?? '')),
				'http'  => $this->hostWithoutPath((string) ($config->httphost ?? '')),
			];

			foreach ($domains as $olddomain)
			{
				$originalOldDomain = $olddomain;

				/**
				 * The old domain and its subdomains, with any port or none (IIS conditions ignore case): without the
				 * right anchor, old.example.com.evil.test matched old.example.com. The rule is named after the old domain
				 * as normaliseOldDomains() returns it: an internationalised one in its punycode form (gh-476).
				 */
				$olddomain     = htmlspecialchars($this->oldDomainHostRegex($olddomain), ENT_XML1 | ENT_QUOTES, 'UTF-8');
				$oldDomainName = htmlspecialchars($originalOldDomain, ENT_XML1 | ENT_QUOTES, 'UTF-8');

				foreach ($schemes as $scheme => $schemeCondition)
				{
					/**
					 * This scheme's host name is the old domain or one of its subdomains, with any port: redirecting it
					 * to itself would loop. E.g. example.com is left out for a site on www.example.com.
					 */
					if ($this->oldDomainCoversHost($originalOldDomain, $newDomains[$scheme]))
					{
						continue;
					}

					$newdomain = htmlspecialchars($newDomains[$scheme], ENT_XML1 | ENT_QUOTES, 'UTF-8');

					$webConfig .= <<<END
				<rule name="Redirect old to new domain ($oldDomainName){$schemeSuffix[$scheme]}" stopProcessing="true">
					<match url="(.*)" ignoreCase="false" />
					<conditions logicalGrouping="MatchAll">
						$schemeCondition
						<add input="{HTTP_HOST}" pattern="$olddomain" />
					</conditions>
					<action type="Redirect" url="$scheme://$newdomain/$subfolder{R:1}" redirectType="Found" />
				</rule>

END;
				}
			}
		}

		if (!empty($config->httpsurls))
		{
			/**
			 * LEGACY FEATURE: "Force HTTPS for these URLs" (httpsurls) will be removed in a future version. It predates
			 * sites served entirely over HTTPS; today the whole site should be on HTTPS. Keep it working, but do not
			 * extend it.
			 *
			 * The path is matched case-sensitively (ignoreCase="false"), although IIS serves the same file whatever the
			 * letter case of the address: /Login is not redirected when the entry is login. This is a documented caveat,
			 * not a bug to fix, given the feature's legacy status.
			 *
			 * IIS sets {HTTPS} to "on" or "off". Behind a reverse proxy or load balancer which terminates TLS, IIS always
			 * receives plain HTTP: X-Forwarded-Proto: https (in any letter case: IIS conditions ignore case by default)
			 * tells it the visitor is on HTTPS already, where redirecting again would loop.
			 */
			$httpsHost  = htmlspecialchars($this->hostWithoutPath((string) ($config->httpshost ?? '')), ENT_XML1 | ENT_QUOTES, 'UTF-8');
			$httpsRules = '';
			$ruleNames  = [];

			/**
			 * Like the .htaccess Maker, skip empty entries: one would match ^$, the site's root. The match url is the path
			 * relative to the web.config's folder, which never starts with a slash: an entry typed with one, e.g. /login,
			 * is normalised to login, otherwise it would never match. See normaliseForceHttpsUrls().
			 */
			foreach ($this->normaliseForceHttpsUrls($config->httpsurls ?? []) as $url)
			{
				[$path, $query] = array_pad(explode('?', $url, 2), 2, null);

				/**
				 * Each entry goes into XML attributes, so it is XML-escaped, after regex escaping for the match url.
				 * Otherwise an entry with &, < or " makes the web.config invalid, and IIS refuses every request with HTTP
				 * 500.19. In the action url, URL Rewrite reads {…} as a server variable or back-reference, e.g. {HTTP_HOST}
				 * or {R:1}: braces are percent-encoded there, which is how browsers send them anyway. So are the % (first)
				 * and the space, which IIS would otherwise put in the Location header as they are: a raw space makes an
				 * invalid header, and a % followed by two hex digits redirects to another URL, e.g. c%1d is c, 0x1D, d.
				 */
				/**
				 * IIS compares rule names regardless of letter case, and refuses a web.config with two rules of the same
				 * name with HTTP 500 for every request (measured, gh-466). normaliseForceHttpsUrls() keeps entries which
				 * only differ in letter case, e.g. login?v=a and login?v=A, or Login and login: they are different URLs.
				 * The second one's rule name gets a number, e.g. login #2. No entry has a #, see normaliseForceHttpsUrls(),
				 * so that is never another entry's name.
				 */
				$ruleName = $url;

				for ($n = 2; isset($ruleNames[$this->foldCase($ruleName)]); $n++)
				{
					$ruleName = $url . ' #' . $n;
				}

				$ruleNames[$this->foldCase($ruleName)] = true;

				$urlName    = htmlspecialchars($ruleName, ENT_XML1 | ENT_QUOTES, 'UTF-8');
				$urlesc     = htmlspecialchars('^' . $this->escape_string_for_regex($path) . '$', ENT_XML1 | ENT_QUOTES, 'UTF-8');
				$urlTarget  = str_replace(
					['%', ' ', '{', '}'], ['%25', '%20', '%7B', '%7D'], htmlspecialchars($path, ENT_XML1 | ENT_QUOTES, 'UTF-8')
				);

				/**
				 * An entry's query string only matches exactly that query string, in the order typed (gh-466), see
				 * queryStringRegex(). {QUERY_STRING} is not URL-decoded. IIS conditions ignore letter case unless told
				 * otherwise. The action url has no query string, and appendQueryString defaults to true: the redirect is
				 * to the same URL over HTTPS.
				 */
				$queryCond = $query === null ? '' : "\n\t\t\t\t\t\t" . '<add input="{QUERY_STRING}" pattern="'
					. htmlspecialchars('^' . $this->queryStringRegex($query) . '$', ENT_XML1 | ENT_QUOTES, 'UTF-8')
					. '" ignoreCase="false" />';
				$httpsRules .= <<<END
				<rule name="Force HTTPS for $urlName" stopProcessing="true">
					<match url="$urlesc" ignoreCase="false" />
					<conditions logicalGrouping="MatchAll">
						<add input="{HTTPS}" pattern="^OFF$" />
						<add input="{HTTP_X_FORWARDED_PROTO}" pattern="^https$" negate="true" />$queryCond
					</conditions>
					<action type="Redirect" url="https://$httpsHost/$subfolder$urlTarget" redirectType="Found" />
				</rule>

END;
			}

			if ($httpsRules !== '')
			{
				$webConfig .= "<!-- Force HTTPS for certain pages -->\n" . $httpsRules;
			}
		}

		$webConfig .= <<<END
				<rule name="Block out some common exploits">
					<match url=".*" ignoreCase="false" />
					<conditions logicalGrouping="MatchAny" trackAllCaptures="false">
						<add input="{QUERY_STRING}" pattern="proc/self/environ" ignoreCase="false" />
						<add input="{QUERY_STRING}" pattern="mosConfig_[a-zA-Z_]{1,21}(=|\%3D)" ignoreCase="false" />
						<add input="{QUERY_STRING}" pattern="base64_(en|de)code\(.*\)" ignoreCase="false" />
						<add input="{QUERY_STRING}" pattern="(&lt;|%3C).*script.*(>|%3E)" />
						<add input="{QUERY_STRING}" pattern="GLOBALS(=|\[|\%[0-9A-Z]{0,2})" ignoreCase="false" />
						<add input="{QUERY_STRING}" pattern="_REQUEST(=|\[|\%[0-9A-Z]{0,2})" ignoreCase="false" />
					</conditions>
					<action type="CustomResponse" url="index.php" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

END;

		if ($config->fileinj == 1)
		{
			/**
			 * See FILE_INJECTION_PATTERNS (gh-485): every condition is case-insensitive. A rule's conditions are either all
			 * ANDed or all ORed, so the patterns are one alternation, ANDed with the negated exempt query (Akeeba Backup's
			 * OAuth2 helper). <match url> leaves out the administrator and api folders, see FILE_INJECTION_EXEMPT_FOLDERS;
			 * it is relative to this web.config's folder, the site's root. No separate exemption rule: stopProcessing on
			 * it would skip every rule after it.
			 */
			$patterns    = htmlspecialchars('(' . implode(')|(', self::FILE_INJECTION_PATTERNS) . ')', ENT_QUOTES | ENT_XML1);
			$exemptQuery = htmlspecialchars(self::FILE_INJECTION_EXEMPT_QUERY, ENT_QUOTES | ENT_XML1);
			$exemptUrl   = htmlspecialchars('^' . self::FILE_INJECTION_EXEMPT_FOLDERS, ENT_QUOTES | ENT_XML1);

			$webConfig .= <<<END
				<rule name="File injection protection" stopProcessing="true">
					<match url="$exemptUrl" negate="true" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
						<add input="{QUERY_STRING}" pattern="$patterns" ignoreCase="true" />
						<add input="{QUERY_STRING}" pattern="$exemptQuery" negate="true" ignoreCase="true" />
					</conditions>
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

END;
		}

		if ($config->leftovers == 1)
		{
			/**
			 * Hide the leftover files in the site's root with a 404, as documented and like the NginX Conf Maker does
			 * (gh-486); it returned 403. It comes before the Server Protection rules, so that front-end protection's 403
			 * for htaccess.txt and web.config.txt does not apply first. Only the site's root: <match url> is anchored,
			 * and relative to the folder of this web.config.
			 */
			$webConfig .= <<<END
				<rule name="Leftover files - Block access to common server configuration files">
					<match url="^(htaccess\.txt|configuration\.php-dist|php\.ini|\.user\.ini|web\.config|web\.config\.txt)$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="CustomResponse" statusCode="404" statusReason="Not Found" statusDescription="Not Found" />
				</rule>

END;
		}

		if ($config->fileorder == 1 && !$indexPhpEverywhere)
		{
			/**
			 * index.php is not a site-wide default document, so the site root, administrator/ and api/ are rewritten to
			 * their index.php here. It does not stop processing: the Server Protection rules below see the rewritten
			 * URL. The folder URLs without a trailing slash are left alone; relative links in their pages would point to
			 * the wrong folder. IIS redirects them to the URL with the trailing slash.
			 */
			$webConfig .= <<<END
				<rule name="Default document - index.php in the Joomla! folders">
					<match url="^(administrator/|api/|)$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="Rewrite" url="{R:1}index.php" />
				</rule>

END;
		}

		$phpExt = self::PHP_EXTENSIONS;

		if ($config->backendprot == 1 || $config->frontendprot == 1)
		{
			/**
			 * Hosts which map PHP by a file's extensions run any file with a PHP extension anywhere in its name, e.g.
			 * x.php.png, as a PHP script. This must come before the exceptions: they all match the last extension of
			 * the file, or the folder alone, so they would let such a file through.
			 */
			$webConfig .= <<<END
				<rule name="Server protection - Forbid PHP double extensions" stopProcessing="true">
					<match url="\.($phpExt)\." ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

END;
		}

		/**
		 * IIS resolves file names case-insensitively: a different letter case names the same file. Every URL path rule
		 * from here on sets ignoreCase="true". A case-sensitive block rule is bypassed with e.g. /Administrator/, and a
		 * case-sensitive allow rule only breaks legitimate requests.
		 */
		$webConfig .= "                <!-- Advanced server protection rules exceptions -->\n";

		if (!empty($config->exceptionfiles))
		{
			$ruleCounter = 0;

			foreach ($config->exceptionfiles as $file)
			{
				$ruleCounter++;
				$entry     = $file;
				// Excepted PHP files must receive the full URL path. XML-escaped: & or < would make IIS refuse the file.
				$pathInfo  = preg_match('#\.(' . $phpExt . ')$#i', $file) ? '(/.*)?' : '';
				$file      = htmlspecialchars(
					'^' . $this->entryRegex($file) . $pathInfo . '$', ENT_XML1 | ENT_QUOTES, 'UTF-8'
				);
				$webConfig .= <<<END
				<rule name="Advanced server protection rules exception #$ruleCounter" stopProcessing="true">
					<match url="$file" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="None" />
				</rule>

END;

				if ($config->frontendprot == 1)
				{
					$webConfig .= $this->exceptionFileFolderRule($entry, $ruleCounter, $config->fileorder == 1, $indexPhpEverywhere);
				}
			}
		}

		if (!empty($config->exceptiondirs))
		{
			$ruleCounter = 0;

			/**
			 * "Except .php files" means every file the server could run as PHP, in any letter case: .phtml, .php5 etc.
			 * as well. Such files fall through to the rest of the server protection rules. Double extensions are
			 * already refused above.
			 *
			 * Front-end protection refuses folder URLs (see "Disallow access to all other front-end folders"), which
			 * IIS would answer with the folder's default document. In these folders it may serve it, unless it is PHP.
			 * index.php can be one with "Force index.php parsing before index.html" off, where the server's own list
			 * applies and typically has it: such a folder is refused. With index.php the default document in every
			 * folder (fileorderscope=all), the site owner's choice, it runs here as everywhere else.
			 */
			$folderCondition = $config->fileorder == 1 ? '' : self::NO_INDEX_PHP_CONDITION;

			foreach ($config->exceptiondirs as $dir)
			{
				$ruleCounter++;
				$dir       = htmlspecialchars($this->entryRegex($dir), ENT_XML1 | ENT_QUOTES, 'UTF-8');
				$webConfig .= <<<END
				<rule name="Allow access to folders except .php files #$ruleCounter" stopProcessing="true">
					<match url="^$dir/" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
						<add input="{URL}" pattern="\.($phpExt)$" ignoreCase="true" negate="true" />
						<add input="{REQUEST_FILENAME}" matchType="IsFile" ignoreCase="false" />
					</conditions>
					<action type="None" />
				</rule>

END;

				if ($config->frontendprot == 1)
				{
					$webConfig .= <<<END
				<rule name="Allow access to folders except .php files #$ruleCounter, folder URLs" stopProcessing="true">
					<match url="^$dir/(?:.*/)?$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
						<add input="{REQUEST_FILENAME}" matchType="IsDirectory" ignoreCase="false" />$folderCondition
					</conditions>
					<action type="None" />
				</rule>

END;
				}
			}
		}

		if (!empty($config->fullaccessdirs))
		{
			$ruleCounter = 0;

			foreach ($config->fullaccessdirs as $dir)
			{
				$ruleCounter++;
				$dir       = htmlspecialchars($this->entryRegex($dir), ENT_XML1 | ENT_QUOTES, 'UTF-8');
				$webConfig .= <<<END
				<rule name="Allow access to folders, including .php files #$ruleCounter" stopProcessing="true">
					<match url="^$dir/" ignoreCase="true" />
					<action type="None" />
				</rule>

END;
			}
		}

		if ($config->backendprot == 1 || $config->frontendprot == 1)
		{
			// Blocked PHP files (except Joomla index files) must not receive path information
			$webConfig .= <<<END
				<rule name="Server protection - Block PATH_INFO after PHP files except for entry points" stopProcessing="true">
					<match url="^(?!index\.php/|api/index\.php/|administrator/index\.php/).*\.($phpExt)/" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

END;
		}

		if ($config->backendprot == 1)
		{
			/**
			 * Both are empty when there is no folder or no file type to allow: the media file rule is then left out.
			 * The folders are XML-escaped after regex escaping: & is a valid character in a folder name.
			 */
			$directories = $this->bugfixBackendProtectionExclusionDirectories(
				$this->normaliseDirectories($config->bepexdirs ?: [])
			);
			$bedirs      = htmlspecialchars($this->directoriesRegex($directories), ENT_XML1 | ENT_QUOTES, 'UTF-8');
			$betypes     = $this->fileTypesRegex($config->bepextypes);
			$webConfig   .= <<<END
				<rule name="Back-end protection - allow administrator login" stopProcessing="true">
					<match url="^administrator/?$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="None" />
				</rule>
				<rule name="Back-end protection - allow administrator login, alternate" stopProcessing="true">
					<match url="^administrator/index\.(php|html?)$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="None" />
				</rule>
				<rule name="Back-end protection - allow administrator with path" stopProcessing="true">
					<match url="^administrator/index\.php/" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="None" />
				</rule>

END;

			if ($bedirs !== '' && $betypes !== '')
			{
				$webConfig .= <<<END
				<rule name="Back-end protection - allow access to static media files" stopProcessing="true">
					<match url="^administrator/($bedirs)/.*\.($betypes)$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="None" />
				</rule>

END;
			}

			/**
			 * Windows reaches the administrator folder by other names than administrator/, in any letter case, which the
			 * catch-all does not match (gh-490). With front-end protection off nothing else refuses them:
			 * - the name with trailing dots or spaces, administrator./ or administrator%20/, which Windows strips;
			 * - the name followed by an NTFS stream, administrator::$INDEX_ALLOCATION/, should IIS let a colon through;
			 * - its 8.3 short name, ADMINI~1/ (~2 etc. when other folders of the site's root start with "admini"), or,
			 *   after the fourth such folder, the first two letters, a four-digit hexadecimal hash and ~1, e.g.
			 *   AD3F2A~1/. Only on a volume with 8.3 name creation on.
			 * Only these forms: any other folder name, e.g. administrator.old/ or administrator-backup/, is a different
			 * folder, which these rules leave alone like before. Every such request is refused, the login page too: the
			 * back-end's own URL is /administrator/.
			 */
			$webConfig .= <<<END
				<rule name="Back-end protection - Catch all">
					<match url="^administrator/" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>
				<rule name="Back-end protection - Catch all, other names of the administrator folder">
					<match url="^(?:administrator[. ]*(?::[^/]*)?|(?:admini|ad[0-9a-f]{4})~[0-9]+[. ]*(?::[^/]*)?)/" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

END;
		}

		if ($config->frontendprot == 1)
		{
			// Both are empty when there is no folder or no file type: the rules which need them are then left out.
			$fedirs    = htmlspecialchars($this->directoriesRegex($config->fepexdirs), ENT_XML1 | ENT_QUOTES, 'UTF-8');
			$fetypes   = $this->fileTypesRegex($config->fepextypes);

			/**
			 * The PHP block rule exempts only the Joomla! entry points: index.php, api/index.php and
			 * administrator/index.php, with or without path info. Not an index.php in any other folder. The exemption
			 * is part of the <match url>, which is relative to the folder of this web.config, so it also works with
			 * Joomla! in a subfolder. A condition on {URL} would see the full URL path, subfolder included.
			 */
			$webConfig .= <<<END
				<rule name="Front-end protection - allow access to additional TinyMCE plugins' HTML files" stopProcessing="true">
					<match url="^media/plg_editors_tinymce/js/plugins/.*\.(htm|html)$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="None" />
				</rule>

END;

			if ($fedirs !== '' && $fetypes !== '')
			{
				$webConfig .= <<<END
				<rule name="Front-end protection - allow access to static media files" stopProcessing="true">
					<match url="^($fedirs)/.*\.($fetypes)$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="None" />
				</rule>

END;
			}

			if ($fedirs !== '')
			{
				$webConfig .= <<<END
				<rule name="Front-end protection - Block access to certain folders">
					<match url="^($fedirs)/" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

END;
			}

			$webConfig .= <<<END
				<rule name="Front-end protection - Block access to certain folders, part 2">
					<match url="^(cache|includes|language|logs|log|tmp)/" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>
				<rule name="Front-end protection - Forbid access to leftover Joomla! files">
					<match url="^(configuration\.php|CONTRIBUTING\.md|htaccess\.txt|joomla\.xml|LICENSE\.txt|phpunit\.xml|README\.txt|web\.config\.txt)" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false" />
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>
				<rule name="Front-end protection - Block access to all PHP files except index.php">
					<match url="^(?!(?:administrator/|api/)?index\.php(?:/|$)).*\.($phpExt)$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
						<add input="{URL}" pattern="\.($phpExt)$" ignoreCase="true" />
						<add input="{REQUEST_FILENAME}" matchType="IsFile" ignoreCase="false" />
					</conditions>
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

END;

			/**
			 * Deny by default, like the .htaccess Maker's "Disallow access to all other front-end files": refuse every
			 * existing file which no rule above let through. Each allow rule above stops processing, so a file it allows
			 * never gets here. Requests which are not files, e.g. SEF URLs, fall through to the SEF rules below.
			 *
			 * Exempt are:
			 * - index.php and api/index.php, with or without path info. The PHP block rule above lets them through, and
			 *   the "Default document" rewrite rule rewrites the site root and api/ to them without stopping;
			 * - robots.txt, which the .htaccess Maker also allows (the NginX Conf Maker refused it, gh-425);
			 * - the common static files of the site's root, e.g. favicon.ico, ads.txt and the search engines' site
			 *   verification files (ROOT_STATIC_FILES), like the other Makers (gh-469). Anchored at both ends: only in
			 *   the site's root. The match ignores letter case. The folders rule below exempts them too, which changes
			 *   nothing: a folder URL ends with a slash, so it never matches them;
			 * - with back-end protection off, the back-end. It is left to the server, like the .htaccess Maker and the
			 *   NginX Conf Maker do (gh-424). With back-end protection on, the back-end rules above take every request
			 *   under administrator/ anyway.
			 *
			 * <match url> is relative to the folder of this web.config, so this also works with Joomla! in a subfolder.
			 */
			$feAllowed = '(?:api/)?index\.php(?:/|$)|robots\.txt$|(?:' . self::ROOT_STATIC_FILES . ')$';

			if ($config->backendprot != 1)
			{
				$feAllowed .= '|administrator(?:/|$)';
			}

			$webConfig .= <<<END
				<rule name="Front-end protection - Disallow access to all other front-end files">
					<match url="^(?!(?:$feAllowed)).*" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
						<add input="{REQUEST_FILENAME}" matchType="IsFile" ignoreCase="false" />
					</conditions>
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

END;

			/**
			 * IIS answers a folder URL, e.g. foo/, with the folder's default document (foo/index.html, foo/index.php
			 * etc.) without running these rules again against the file it serves. The deny rule above and the PHP block
			 * rule only see foo/, which is not a file. Apache runs mod_rewrite again for the default document, so the
			 * .htaccess Maker has no such gap. Refuse every existing folder which no rule above let through, whatever
			 * its default document: with "Force index.php parsing before index.html" off the server's own list
			 * applies, which can name anything. A folder without one would be refused, or listed, anyway.
			 *
			 * Only folder URLs with a trailing slash: IIS redirects the ones without it, and serves nothing. Exempt are
			 * the site root (the empty URL, which the pattern cannot match), api/ and whatever the deny rule exempts.
			 * The "including .php files" and "except .php files" folders have their own allow rules above. With
			 * index.php the default document in every folder, which the site owner chose, a folder holding one runs
			 * it.
			 */
			$folderCondition = ($config->fileorder == 1 && $indexPhpEverywhere) ? self::NO_INDEX_PHP_CONDITION : '';

			$webConfig .= <<<END
				<rule name="Front-end protection - Disallow access to all other front-end folders">
					<match url="^(?!(?:$feAllowed|api/$)).*/$" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
						<add input="{REQUEST_FILENAME}" matchType="IsDirectory" ignoreCase="false" />$folderCondition
					</conditions>
					<action type="CustomResponse" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

END;
		}

		// The <script> pattern had < and > swapped; it is now the same as the "Block out some common exploits" rule's (gh-491).
		$webConfig .= <<< XML
				<rule name="Joomla! Common Exploits Prevention" stopProcessing="true">
					<match url="^(.*)$" ignoreCase="false" />
					<conditions logicalGrouping="MatchAny" trackAllCaptures="false">
						<add input="{QUERY_STRING}" pattern="base64_encode[^(]*\([^)]*\)" ignoreCase="false" />
						<add input="{QUERY_STRING}" pattern="(&lt;|%3C)([^s]*s)+cript.*(>|%3E)" />
						<add input="{QUERY_STRING}" pattern="GLOBALS(=|\[|\%[0-9A-Z]{0,2})" ignoreCase="false" />
						<add input="{QUERY_STRING}" pattern="_REQUEST(=|\[|\%[0-9A-Z]{0,2})" ignoreCase="false" />
					</conditions>
					<action type="CustomResponse" url="index.php" statusCode="403" statusReason="Forbidden" statusDescription="Forbidden" />
				</rule>

XML;

		/**
		 * {URL} is the whole URL path, URL-decoded, also in the web.config of a site in a subfolder, so the conditions
		 * keeping index.php and api/index.php from being rewritten to themselves start with the "Base directory of your
		 * site", escaped with pathRegex() (a space is \x20), like the .htaccess Maker's (gh-463). They were ^/api/index.php
		 * and ^/index.php, which never matched for a site in a subfolder, and whose unescaped dots matched any character:
		 * a SEF URL such as index-php, or api/index-php, was not rewritten to the index.php it belongs to (gh-464). For a
		 * site in the domain's root they are ^/api/index\.php and ^/index\.php. A request for index.php or api/index.php
		 * with path info is not rewritten either way, as IIS finds its {REQUEST_FILENAME} is a file (measured).
		 */
		$sefSitePath = $sitePath === ''
			? '' : htmlspecialchars('/' . $this->pathRegex($sitePath), ENT_XML1 | ENT_QUOTES, 'UTF-8');

		$webConfig .= <<< XML
			<rule name="Joomla! API Application SEF URLs">
               <match url="^api/(.*)" ignoreCase="false" />
               <conditions logicalGrouping="MatchAll">
                 <add input="{URL}" pattern="^$sefSitePath/api/index\.php" ignoreCase="true" negate="true" />
                 <add input="{REQUEST_FILENAME}" matchType="IsFile" ignoreCase="false" negate="true" />
                 <add input="{REQUEST_FILENAME}" matchType="IsDirectory" ignoreCase="false" negate="true" />
               </conditions>
               <action type="Rewrite" url="api/index.php" />
           </rule>

XML;

		$webConfig .= <<< XML
				<rule name="Joomla! SEF Rule 2">
					<match url="(.*)" ignoreCase="false" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
						<add input="{URL}" pattern="^$sefSitePath/index\.php" ignoreCase="true" negate="true" />
						<add input="{REQUEST_FILENAME}" matchType="IsFile" ignoreCase="false" negate="true" />
						<add input="{REQUEST_FILENAME}" matchType="IsDirectory" ignoreCase="false" negate="true" />
					</conditions>
					<action type="Rewrite" url="index.php" />
				</rule>

			</rules>

XML;

		$expirationRules = $config->exptime != 0 ? $this->expirationRules($config) : '';

		if ($config->noserversignature == 1 || $config->svgneutralise == 1 || $expirationRules !== '')
		{
			/**
			 * IIS merges a folder's web.config with its parents'. Without <clear />, a site in a subfolder of another, both
			 * with an Admin Tools web.config, inherits the parent's rule: a duplicate name, which IIS refuses with HTTP
			 * 500.52 on every request to the subfolder. The inbound <rules> start with <clear /> for the same reason, and
			 * so do the expiration rules' <preConditions>.
			 */
			$webConfig .= <<< XML
		<outboundRules>
			<clear />

XML;

			if ($config->noserversignature == 1)
			{
				/**
				 * X-Powered-By and X-Content-Powered-By are blanked, which makes IIS drop them (gh-487). The <customHeaders>
				 * entries below only replace an inherited entry, e.g. ASP.NET's; IIS merges their value into the header PHP
				 * sends with expose_php on, which kept PHP's version. Outbound rules see the merged header. These rules
				 * must come before the expiration time rules, which stop processing the outbound rules.
				 */
				$webConfig .= <<< XML
		  <rule name="Remove IIS version signature">
			<match serverVariable="RESPONSE_Server" pattern=".+" />
			<action type="Rewrite" value="MYOB" />
		  </rule>
		  <rule name="Remove PHP version signature">
			<match serverVariable="RESPONSE_X_Powered_By" pattern=".+" />
			<action type="Rewrite" value="" />
		  </rule>
		  <rule name="Remove PHP version signature, X-Content-Powered-By">
			<match serverVariable="RESPONSE_X_Content_Powered_By" pattern=".+" />
			<action type="Rewrite" value="" />
		  </rule>

XML;
			}

			$webConfig .= $this->svgNeutraliseRules($config);
			$webConfig .= $expirationRules;

			$webConfig .= <<< XML
		</outboundRules>

XML;
		}

		/**
		 * Every named collection entry is removed before it is added: <customHeaders> here, and the <verbs> and
		 * <ipSecurity> entries. A site in a subfolder of another, both with an Admin Tools web.config, inherits the
		 * parent's entries, and IIS refuses an entry added twice under the same key (HTTP 500.19). Unlike <clear />, this
		 * keeps the entries the server itself sets, e.g. a host's own headers or denied verbs.
		 */
		$webConfig .= <<< XML
		</rewrite>
		<httpProtocol>
			<customHeaders>

XML;

		if ($config->clickjacking == 1)
		{
			$webConfig .= <<< ENDCONF
				<!-- Protect against clickjacking / Forbid displaying in FRAME -->
				<remove name="X-Frame-Options" />
				<add name="X-Frame-Options" value="SAMEORIGIN" />

ENDCONF;
		}

		if ($config->reducemimetyperisks == 1)
		{
			$webConfig .= <<< XML
				<!-- Reduce MIME type security risks -->
				<remove name="X-Content-Type-Options" />
				<add name="X-Content-Type-Options" value="nosniff" />

XML;
		}

		if ($config->reflectedxss == 1)
		{
			$webConfig .= <<< XML
				<!-- Reflected XSS prevention -->
				<remove name="X-XSS-Protection" />
				<add name="X-XSS-Protection" value="1; mode=block" />

XML;
		}

		if ($config->noserversignature == 1)
		{
			$webConfig .= <<< XML
				<!-- Remove IIS and PHP version signature -->
				<remove name="X-Powered-By" />
				<add name="X-Powered-By" value="MYOB" />
				<remove name="X-Content-Powered-By" />
				<add name="X-Content-Powered-By" value="MYOB" />

XML;

		}

		if ($config->notransform == 1)
		{
			$webConfig .= <<< XML
				<!-- Prevent content transformation -->
				<remove name="Cache-Control" />
				<add name="Cache-Control" value="no-transform" />

XML;
		}

		if ($config->hstsheader == 1)
		{
			$webConfig .= <<<XML
				<!-- HSTS Header - See http://en.wikipedia.org/wiki/HTTP_Strict_Transport_Security -->
				<remove name="Strict-Transport-Security" />
				<add name="Strict-Transport-Security" value="max-age=31536000" />

XML;
		}
		elseif ($config->hstsheader == 2)
		{
			$webConfig .= <<<XML
				<!-- HSTS Header - See http://en.wikipedia.org/wiki/HTTP_Strict_Transport_Security -->
				<remove name="Strict-Transport-Security" />
				<add name="Strict-Transport-Security" value="max-age=31536000; includeSubDomains; preload" />

XML;
		}

		if ($config->cors == 1)
		{
			$webConfig .= <<<XML
				<!-- Explicitly enable Cross-Origin Resource Sharing (CORS) - See http://enable-cors.org/ -->
				<remove name="Access-Control-Allow-Origin" />
				<add name="Access-Control-Allow-Origin" value="*" />
				<remove name="Timing-Allow-Origin" />
				<add name="Timing-Allow-Origin" value="*" />

XML;
		}
		elseif ($config->cors == -1)
		{
			$webConfig .= <<<XML
				<!-- Explicitly disable Cross-Origin Resource Sharing (CORS) - See http://enable-cors.org/ -->
				<remove name="Cross-Origin-Resource-Policy" />
				<add name="Cross-Origin-Resource-Policy" value="same-origin" />

XML;
		}

		if ($config->referrerpolicy !== '-1')
		{
			$webConfig .= <<<XML
				<!-- Referrer-policy -->
				<remove name="Referrer-Policy" />
				<add name="Referrer-Policy" value="{$config->referrerpolicy}" />

XML;
		}

		$webConfig .= <<< XML
			</customHeaders>
		</httpProtocol>

XML;

		// If IP restriction is turned on, this block is moved towards the top of the web.config file.
		if ($config->notracetrack == 1 && $restrictIP === 'none')
		{
			$webConfig .= <<<XML
		<!-- Disable HTTP methods TRACE and TRACK (protect against XST) -->
		<security>
			<requestFiltering>
				<verbs>
					<remove verb="TRACE" />
					<add verb="TRACE" allowed="false" />
					<remove verb="TRACK" />
					<add verb="TRACK" allowed="false" />
				</verbs>
			</requestFiltering>
		</security>

XML;
		}

		$webConfig .= <<< XML
	</system.webServer>

XML;

		/**
		 * The full-access folders typically hold another PHP application, e.g. a WordPress in a subfolder. index.php is
		 * the default document in them and their subfolders, as it would be site-wide with 'all'.
		 */
		if ($config->fileorder == 1 && !$indexPhpEverywhere)
		{
			foreach ($config->fullaccessdirs ?: [] as $dir)
			{
				$dir       = htmlspecialchars($dir, ENT_QUOTES | ENT_XML1, 'UTF-8');
				$webConfig .= <<< XML
	<location path="$dir">
		<system.webServer>
			<defaultDocument enabled="true">
				<files>
					<clear />
					<add value="index.php" />
					<add value="index.html" />
					<add value="index.htm" />
				</files>
			</defaultDocument>
		</system.webServer>
	</location>

XML;
			}
		}

		$webConfig .= <<< XML
</configuration>

XML;

		return $webConfig;
	}

	/**
	 * The rule letting the folder URL of an "Allow direct access to these files" entry through, when IIS would answer it
	 * with that file as the folder's default document, e.g. docs/ for docs/index.html. Front-end protection refuses
	 * folder URLs otherwise (see "Disallow access to all other front-end folders"), while Apache serves them: it runs
	 * mod_rewrite again for the default document, which the file's own exception then allows.
	 *
	 * Only a name on the default document list counts, and only if the folder holds none of the names IIS would pick
	 * first. With "Force index.php parsing before index.html" on, that list is the web.config's own. Otherwise it is the
	 * server's, which the web.config cannot know: IIS's default list, plus index.php, as on a typical PHP-on-IIS host. As
	 * its order may differ, none of its other names may exist in the folder. An entry in the site's root needs no rule:
	 * front-end protection never refuses the site's root URL.
	 *
	 * @param   string  $entry               The entry, e.g. docs/index.html
	 * @param   int     $number              The entry's number, as in the name of its own exception rule
	 * @param   bool    $ownList             Does the web.config set the default document list (fileorder=1)?
	 * @param   bool    $indexPhpEverywhere  Is index.php the first default document in every folder (fileorderscope=all)?
	 *
	 * @return  string  The rule, or an empty string if the entry needs none
	 */
	private function exceptionFileFolderRule(string $entry, int $number, bool $ownList, bool $indexPhpEverywhere): string
	{
		$entry = trim($entry, '/');
		$slash = strrpos($entry, '/');

		if ($slash === false)
		{
			return '';
		}

		$folder = substr($entry, 0, $slash);
		$name   = strtolower(substr($entry, $slash + 1));

		if ($ownList)
		{
			$list     = $indexPhpEverywhere ? ['index.php', 'index.html', 'index.htm'] : ['index.html', 'index.htm'];
			$position = array_search($name, $list, true);

			if ($position === false)
			{
				return '';
			}

			$others = array_slice($list, 0, $position);
		}
		else
		{
			if (!in_array($name, self::SERVER_DEFAULT_DOCUMENTS, true))
			{
				return '';
			}

			$others = array_values(array_diff(self::SERVER_DEFAULT_DOCUMENTS, [$name]));
		}

		$conditions = "\t\t\t\t\t\t<add input=\"{REQUEST_FILENAME}$name\" matchType=\"IsFile\" ignoreCase=\"false\" />\n";

		foreach ($others as $other)
		{
			$conditions .= "\t\t\t\t\t\t<add input=\"{REQUEST_FILENAME}$other\" matchType=\"IsFile\" ignoreCase=\"false\" negate=\"true\" />\n";
		}

		$url = htmlspecialchars('^' . $this->entryRegex($folder) . '/$', ENT_QUOTES | ENT_XML1, 'UTF-8');

		return <<<END
				<rule name="Advanced server protection rules exception #$number, folder URL" stopProcessing="true">
					<match url="$url" ignoreCase="true" />
					<conditions logicalGrouping="MatchAll" trackAllCaptures="false">
$conditions					</conditions>
					<action type="None" />
				</rule>

END;
	}

	/**
	 * The outbound rules of "Neutralise SVG script execution": the policy of the .htaccess and NginX Conf Makers,
	 * script-src 'none', for every .svg and .svgz URL wherever it is and in any letter case, like the NginX Conf Maker
	 * (gh-484). <customHeaders> cannot be limited to some files, and <location> takes no wildcards.
	 *
	 * The web.config Maker writes no other Content-Security-Policy. One the response already has, e.g. from the server's
	 * own <customHeaders>, is kept: the first rule adds the SVG policy to it, as a policy of its own, which a browser
	 * enforces alongside the other. Rewriting the header would replace a stricter policy with this one. The second rule
	 * writes the header when there is none; after the first one, it no longer matches.
	 *
	 * They must come before the expiration time rules: the one for image files, image/svg+xml among them, stops
	 * processing the outbound rules.
	 *
	 * @param   object  $config  The web.config Maker configuration
	 *
	 * @return  string
	 * @since   7.10.0
	 */
	private function svgNeutraliseRules($config): string
	{
		if ($config->svgneutralise != 1)
		{
			return '';
		}

		return <<< XML
			<!-- Neutralise SVG script execution -->
			<rule name="Neutralise SVG script execution, with another policy">
				<match serverVariable="RESPONSE_Content_Security_Policy" pattern=".+" />
				<conditions>
					<add input="{URL}" pattern="\.svgz?$" ignoreCase="true" />
				</conditions>
				<action type="Rewrite" value="{R:0}, script-src 'none'" />
			</rule>
			<rule name="Neutralise SVG script execution">
				<match serverVariable="RESPONSE_Content_Security_Policy" pattern="^$" />
				<conditions>
					<add input="{URL}" pattern="\.svgz?$" ignoreCase="true" />
				</conditions>
				<action type="Rewrite" value="script-src 'none'" />
			</rule>

XML;
	}

	/**
	 * The expiration time of each kind of static file, in seconds, and the most common one ('default').
	 *
	 * They are the .htaccess Maker's, where mod_expires counts a week as 7 days, a month as 30 days and a year as 365
	 * days: with exptime 1, one week for CSS, JavaScript and fonts, one month for images, audio and video; with exptime
	 * 2, one year for all of them. Either way, no caching for XML, JSON and application cache manifests, and one hour
	 * for RSS and Atom feeds.
	 *
	 * @param   object  $config  The web.config Maker configuration
	 *
	 * @return  int[]
	 * @since   7.10.0
	 */
	private function expirationTimes($config): array
	{
		$week  = ($config->exptime == 2) ? 31536000 : 604800;
		$month = ($config->exptime == 2) ? 31536000 : 2592000;

		return [
			'default' => $month,
			'nocache' => 0,
			'feeds'   => 3600,
			'cssjs'   => $week,
			'images'  => $month,
			'fonts'   => $week,
			'audio'   => $month,
			'video'   => $month,
		];
	}

	/**
	 * The outbound rules which give each kind of static file the .htaccess Maker's expiration time.
	 *
	 * <clientCache> has a single max-age for every static file. It is set to the most common expiration time; every
	 * response which still carries exactly that max-age is a static file, as only IIS' static file handler reads
	 * <clientCache>, and none of these rules touches any other response, e.g. the output of a PHP file. A rule per kind
	 * of file, picked by its Content-Type like mod_expires' ExpiresByType does, replaces that max-age with the kind's own,
	 * keeping anything after it, such as the "no-transform" of "Prevent content transformation". The last rule removes
	 * it from every other static file, which the .htaccess Maker does not give an expiration time either.
	 *
	 * The MIME types are the .htaccess Maker's, plus the ones IIS itself uses for .woff (font/x-woff) and .avi (video/avi)
	 * files. IIS serves .ttf files as application/octet-stream, which no rule can tell apart from any other download.
	 *
	 * @param   object  $config  The web.config Maker configuration
	 *
	 * @return  string
	 * @since   7.10.0
	 */
	private function expirationRules($config): string
	{
		$times  = $this->expirationTimes($config);
		$marker = 'max-age=' . $times['default'];
		$groups = [
			'nocache' => [
				'XML, JSON and application cache manifests',
				['text/cache-manifest', 'application/json', 'application/xml', 'text/xml'],
			],
			'feeds'   => [
				'RSS and Atom feeds',
				['application/atom+xml', 'application/rss+xml'],
			],
			'cssjs'   => [
				'CSS and JavaScript',
				['text/css', 'text/javascript', 'application/javascript', 'application/ld+json', 'application/x-javascript'],
			],
			'images'  => [
				'Image files',
				[
					'application/ico', 'application/smil', 'application/vnd.wap.wbxml', 'image/bmp', 'image/gif', 'image/ico',
					'image/icon', 'image/jp2', 'image/jpeg', 'image/jpg', 'image/pipeg', 'image/png', 'image/svg+xml',
					'image/tiff', 'image/vnd.microsoft.icon', 'image/vnd.wap.wbmp', 'image/webp', 'image/x-icon', 'text/ico',
				],
			],
			'fonts'   => [
				'Font files',
				[
					'application/font-woff', 'application/font-woff2', 'application/vnd.ms-fontobject',
					'application/x-font-opentype', 'application/x-font-ttf', 'application/x-font-woff', 'font/opentype',
					'font/otf', 'font/ttf', 'font/woff', 'font/woff2', 'font/x-woff',
				],
			],
			'audio'   => [
				'Audio files',
				[
					'application/ogg', 'audio/3gpp', 'audio/3gpp2', 'audio/aac', 'audio/basic', 'audio/mid', 'audio/midi',
					'audio/mp3', 'audio/mpeg', 'audio/ogg', 'audio/opus', 'audio/x-aiff', 'audio/x-mpegurl',
					'audio/x-pn-realaudio', 'audio/x-wav', 'audio/wav',
				],
			],
			'video'   => [
				'Movie files',
				[
					'application/x-shockwave-flash', 'video/3gpp', 'video/3gpp2', 'video/mp4', 'video/mpeg', 'video/ogg',
					'video/quicktime', 'video/webm', 'video/x-la-asf', 'video/x-ms-asf', 'video/x-msvideo', 'video/avi',
					'x-world/x-vrml',
				],
			],
		];

		$preConditions = '';
		$rules         = '';

		foreach ($groups as $key => [$label, $mimeTypes])
		{
			$name    = 'Admin Tools expiration time: ' . $label;
			$pattern = '^(' . implode('|', array_map(fn($type) => $this->escape_string_for_regex($type), $mimeTypes)) . ')\s*(;|$)';
			$maxAge  = $times[$key];

			$preConditions .= <<< XML
				<preCondition name="$name">
					<add input="{RESPONSE_CONTENT_TYPE}" pattern="$pattern" />
				</preCondition>

XML;
			$rules         .= <<< XML
			<rule name="Expiration time: $label" preCondition="$name" stopProcessing="true">
				<match serverVariable="RESPONSE_Cache_Control" pattern="^$marker(,.*)?$" />
				<action type="Rewrite" value="max-age=$maxAge{R:1}" />
			</rule>

XML;
		}

		return <<< XML
			<!-- Optimal default expiration time, by file type -->
			<preConditions>
				<clear />
$preConditions			</preConditions>
$rules			<rule name="Expiration time: other static files">
				<match serverVariable="RESPONSE_Cache_Control" pattern="^$marker,?(.*)$" />
				<action type="Rewrite" value="{R:1}" />
			</rule>

XML;
	}

	/**
	 * A number of seconds as an IIS configuration timespan, [d.]hh:mm:ss, e.g. 604800 as 7.00:00:00.
	 *
	 * @param   int  $seconds  A duration, in seconds; zero or more
	 *
	 * @return  string
	 */
	private function secondsToTimespan(int $seconds): string
	{
		$seconds = max(0, $seconds);
		$days    = intdiv($seconds, 86400);
		$time    = sprintf('%02d:%02d:%02d', intdiv($seconds % 86400, 3600), intdiv($seconds % 3600, 60), $seconds % 60);

		return $days > 0 ? $days . '.' . $time : $time;
	}

	private function ipRangeToIPandNetmask(string $ipRange): array
	{
		$ipRange = explode('/', IpExpressionValidator::normalise($ipRange));
		$ip      = $ipRange[0];
		$cidr    = $ipRange[1] ?? null;
		$isIPv4 = filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4);
		$cidr ??= $isIPv4 ? 32 : 128;
		$isNumeric = preg_match('/^\d+$/', $cidr);

		if (!$isNumeric)
		{
			$netmask = $cidr;
		}
		elseif ($isIPv4)
		{
			$cidr = min(max($cidr, 0), 32);
			$netmask = long2ip(~((1 << (32 - $cidr)) - 1));
		}
		else
		{
			$cidr     = min(max($cidr, 0), 128);
			$mask     = str_repeat('1', $cidr) . str_repeat('0', 128 - $cidr);
			$segments = str_split($mask, 16);
			$hextet   = array_map(
				function ($segment) {
					return str_pad(dechex(bindec($segment)), 4, '0', STR_PAD_LEFT);
				}, $segments
			);

			$netmask = implode(':', $hextet);
		}

		return [$ip, $netmask];
	}

	/**
	 * A string in lower case, as IIS compares the names of a web.config's rules, regardless of letter case.
	 *
	 * @param   string  $string  The string, UTF-8
	 *
	 * @return  string
	 * @since   7.10.0
	 */
	private function foldCase(string $string): string
	{
		return function_exists('mb_strtolower') ? mb_strtolower($string, 'UTF-8') : strtolower($string);
	}

	/**
	 * A blocked user agent as a regular expression for IIS, or null if it is skipped, see makeConfigFile(): one with a
	 * control character other than white space, see userAgentRegex(), one which is not a valid regular expression, and
	 * one with PCRE-only syntax IIS cannot compile, see isIisRegex().
	 *
	 * @param   string  $agent  The user agent, see normaliseUserAgents()
	 *
	 * @return  string|null
	 * @since   7.10.0
	 */
	protected function blockedUserAgentRegex(string $agent): ?string
	{
		$regex = parent::blockedUserAgentRegex($agent);

		return ($regex !== null && $this->isIisRegex($regex)) ? $regex : null;
	}

	/**
	 * Does this regular expression have a back-reference, \1 to \9, outside a character class?
	 *
	 * An escaped backslash, \\1, is not one, and neither is \1 in a character class, a character to PCRE. PCRE's \g1 is
	 * not one to IIS, which reads it as g1 (measured, gh-463), and isIisRegex() skips an agent with it (gh-464). This
	 * errs on the side of finding one: such an agent only gets a User-Agent condition of its own.
	 *
	 * @param   string  $regex  The regular expression
	 *
	 * @return  bool
	 * @since   7.10.0
	 */
	private function hasBackReference(string $regex): bool
	{
		$length  = strlen($regex);
		$inClass = false;

		for ($i = 0; $i < $length; $i++)
		{
			$char = $regex[$i];

			if ($char === '\\')
			{
				$next = $regex[$i + 1] ?? '';

				if (!$inClass && $next !== '' && strpos('123456789', $next) !== false)
				{
					return true;
				}

				$i++;

				continue;
			}

			if ($char === '[')
			{
				$inClass = true;
			}
			elseif ($char === ']')
			{
				$inClass = false;
			}
		}

		return false;
	}

	/**
	 * Does this valid PCRE regular expression, see isValidRegex(), have none of the PCRE-only syntax IIS's URL Rewrite
	 * refuses?
	 *
	 * URL Rewrite's regular expressions are ECMAScript-like. Measured on IIS 10 with URL Rewrite 2.1 (gh-462), a pattern
	 * with any of these made it answer every request with HTTP 500.52:
	 * - a group starting with (? other than (?:, (?= and (?!: lookbehind (?<=, (?<!, named groups (?<n>, (?P<n>, inline
	 *   options (?i), atomic groups (?>, comments (?#;
	 * - a possessive quantifier, a + after another quantifier: a++, a?+, a{2}+;
	 * - a brace which is not part of a quantifier {n}, {n,} or {n,m}, e.g. \p{L}, a{,2} or a lone { or };
	 * - a ] which does not end a character class, e.g. a]b, or which starts one, e.g. []a] or [^]a]: PCRE reads it as
	 *   a literal.
	 * IIS accepted lookahead, non-capturing groups, lazy quantifiers, back-references and escapes such as \A and \Q,
	 * whatever they mean to it. It also accepted \g outside a character class, but reads it as the letter g (measured,
	 * gh-463), where PCRE reads \g1, \g{1}, \g{-1}, \g<1> and \g'1' as back-references or subroutine calls: the same entry
	 * would block other user agents on IIS than on Apache and NginX, so it is refused too (gh-464). In a character class,
	 * [\g] is the letter g to both. Any other difference is not checked: this is an approximation, which errs on the side
	 * of skipping an entry.
	 *
	 * @param   string  $regex  The regular expression, valid PCRE
	 *
	 * @return  bool
	 * @since   7.10.0
	 */
	private function isIisRegex(string $regex): bool
	{
		$length     = strlen($regex);
		$quantified = false;

		for ($i = 0; $i < $length; $i++)
		{
			$char = $regex[$i];

			/**
			 * An escaped character, e.g. \( or \{, is a literal, or a character class such as \s. Except \g: to PCRE, \g1,
			 * \g{1}, \g<1> etc. are back-references or subroutine calls, but IIS reads \g as the letter g (gh-464).
			 */
			if ($char === '\\')
			{
				if (($regex[$i + 1] ?? '') === 'g')
				{
					return false;
				}

				$i++;
				$quantified = false;

				continue;
			}

			// A character class: skip it. A ] right after [ or [^ is a literal to PCRE, which IIS refuses.
			if ($char === '[')
			{
				$i += ($regex[$i + 1] ?? '') === '^' ? 2 : 1;

				if (($regex[$i] ?? '') === ']')
				{
					return false;
				}

				while ($i < $length && $regex[$i] !== ']')
				{
					// A POSIX class, e.g. [:alpha:], which IIS accepts
					if ($regex[$i] === '[' && ($regex[$i + 1] ?? '') === ':' && ($end = strpos($regex, ':]', $i + 2)) !== false)
					{
						$i = $end + 2;

						continue;
					}

					$i += $regex[$i] === '\\' ? 2 : 1;
				}

				$quantified = false;

				continue;
			}

			if ($char === '(' && ($regex[$i + 1] ?? '') === '?' && strpos(':=!', $regex[$i + 2] ?? '') === false)
			{
				return false;
			}

			if ($char === '+' && $quantified)
			{
				return false;
			}

			if ($char === '{')
			{
				if (!preg_match('/\G\{\d+(,\d*)?\}/', $regex, $match, 0, $i))
				{
					return false;
				}

				$i          += strlen($match[0]) - 1;
				$quantified = true;

				continue;
			}

			if ($char === '}' || $char === ']')
			{
				return false;
			}

			// A lazy ?, as in a*?, counts as a quantifier too: a + after it, a*?+, is refused as well.
			$quantified = strpos('*+?', $char) !== false;
		}

		return true;
	}
}